'use strict';
const fs=require('fs'), path=require('path'), os=require('os'), assert=require('assert');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'raq-hold-test-'));
const config=require('../src/config');
const src=path.join(root,'src'), dst=path.join(root,'dst');
fs.mkdirSync(path.join(src,'media-hold'),{recursive:true});fs.mkdirSync(path.join(src,'sessions','main'),{recursive:true});
fs.writeFileSync(path.join(src,'media-hold','5.jpg'),'held-image');
fs.writeFileSync(path.join(src,'sessions','main','creds.json'),'private-session');
config.config.paths.database=path.join(src,'bot.sqlite');config.config.paths.sessions=path.join(src,'sessions');
const db=require('better-sqlite3')(config.config.paths.database);db.exec('CREATE TABLE test(k TEXT); INSERT INTO test VALUES (\'value\')');db.close();
process.env.PERSIST_HOLD_MEDIA='1';
const t=require('../src/persist')._test;
(async()=>{
 process.env.PERSIST_HOLD_MEDIA='0'; const without=t.stateHash();
 fs.writeFileSync(path.join(src,'media-hold','5.jpg'),'changed-while-disabled'); assert.equal(t.stateHash(),without); console.log('✓ held media is excluded until explicitly enabled');
 process.env.PERSIST_HOLD_MEDIA='1'; const before=t.stateHash(); fs.writeFileSync(path.join(src,'media-hold','5.jpg'),'held-image-updated');
 assert.notEqual(t.stateHash(),before);console.log('✓ held media changes the cloud snapshot key');
 const snap=await t.snapshot();
 config.config.paths.database=path.join(dst,'bot.sqlite');config.config.paths.sessions=path.join(dst,'sessions');
 const result=await t.restoreFromZip(snap.zipPath);
 assert.equal(result.dbRestored,true);assert.equal(fs.readFileSync(path.join(dst,'media-hold','5.jpg'),'utf8'),'held-image-updated');
 assert.equal(fs.readFileSync(path.join(dst,'sessions','main','creds.json'),'utf8'),'private-session');
 console.log('✓ cloud snapshot restores held media, database and session to a clean location');
 fs.writeFileSync(path.join(dst,'media-hold','5.jpg'),'local-newer');await t.restoreFromZip(snap.zipPath);
 assert.equal(fs.readFileSync(path.join(dst,'media-hold','5.jpg'),'utf8'),'local-newer');
 console.log('✓ cloud restore does not overwrite existing held media');
 fs.rmSync(path.dirname(snap.zipPath),{recursive:true,force:true});
 console.log('PASS: 4 cloud media checks');
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>fs.rmSync(root,{recursive:true,force:true}));
